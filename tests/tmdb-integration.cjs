const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const app = path.join(root, 'app');
const html = fs.readFileSync(path.join(app, 'index.html'), 'utf8');
const packaging = fs.readFileSync(path.join(app, 'tizen_web_project.yaml'), 'utf8');
const manifest = JSON.parse(fs.readFileSync(path.join(app, 'assets/streaming/manifest.json'), 'utf8'));
for (const f of ['data/tmdb-catalog.js','data/tmdb-demo-catalog.js','services/tmdb-content-service.js']) {
  assert.ok(fs.existsSync(path.join(app,f)), `Missing ${f}`);
  assert.ok(html.includes(`src="${f}"`), `Not loaded: ${f}`);
  assert.ok(packaging.includes(`- ${f}`), `Not packaged: ${f}`);
}
assert.ok(packaging.includes('- assets/streaming/manifest.json'));
assert.equal(manifest.assets.length, 0, 'No assets should be recorded before a credentialed import');
assert.ok(fs.existsSync(path.join(app,'assets/streaming/content/fallback-landscape.svg')));
const context = { window: { localStorage: { value: null, getItem() { return this.value; }, setItem(k,v) { this.value=v; } } } };
for (const file of ['data/tmdb-catalog.js','data/tmdb-demo-catalog.js','services/tmdb-content-service.js']) vm.runInNewContext(fs.readFileSync(path.join(app,file),'utf8'),context);
const service=context.window.TMDBContentService;
assert.equal(service.isDemoModeEnabled(), true);
assert.equal(service.getCatalog().length, 0);
assert.equal(service.createDemoContent().length, 10);
assert.ok(service.createDemoContent().every(item=>item.isDemo && !item.availability));
assert.equal(service.createDemoContent().find(item=>item.id==='the-witcher').tmdbId, null);
assert.equal(service.getImage('bad-id','poster'),'');
service.setDemoModeEnabled(false);
assert.equal(service.isDemoModeEnabled(), false);
service.setDemoModeEnabled(true);
assert.equal(service.isDemoModeEnabled(), true);
const importer=fs.readFileSync(path.join(root,'scripts/refresh-tmdb-catalog.cjs'),'utf8');
assert.match(importer,/TMDB_API_KEY/);
assert.match(importer,/Authorization: 'Bearer '/);
assert.match(importer,/\/configuration/);
assert.match(importer,/\/search\/tv/);
assert.match(importer,/\/season\//);
assert.match(importer,/https:\/\/image\.tmdb\.org\/t\/p/);
assert.match(importer,/poster_sizes/);
assert.match(importer,/backdrop_sizes/);
assert.match(importer,/playable:false/);
assert.match(fs.readFileSync(path.join(app,'services/dynamic-wallpaper-service.js'),'utf8'),/setProviderWallpaper/);
assert.match(fs.readFileSync(path.join(app,'main.js'),'utf8'),/renderStreamingPreview/);
assert.match(fs.readFileSync(path.join(app,'main.js'),'utf8'),/setContentWallpaper\(content\)/);
assert.match(fs.readFileSync(path.join(app,'components/continue-watching/ContinueWatching.js'),'utf8'),/isDemoModeEnabled/);
assert.match(fs.readFileSync(path.join(app,'components/continue-watching/ContinueWatching.js'),'utf8'),/Do not move remote focus during initialization/);
assert.match(fs.readFileSync(path.join(app,'tizen-service.js'),'utf8'),/getAppsInfo/);
assert.match(fs.readFileSync(path.join(app,'tizen-service.js'),'utf8'),/launchApp/);
assert.doesNotMatch(importer,/\b(?:api_key|token)\s*[:=]\s*['"][^'"]{8}/i);
console.log('PASS: TMDB catalog load, separated demo mode, local manifest, fallbacks, auth/importer guards.');
